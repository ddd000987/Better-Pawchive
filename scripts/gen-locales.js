/* Generates src/locales/index.ts, the registry of UI languages, from the
 * locale files in src/locales/ (one file per language; the file name is the
 * language code, e.g. zh-tw.ts).
 * Usage: node scripts/gen-locales.js          write the registry
 *        node scripts/gen-locales.js --check  fail if it is out of date
 */
const fs = require('fs')
const path = require('path')

const dir = path.resolve(__dirname, '..', 'src', 'locales')
const target = path.join(dir, 'index.ts')
const codePattern = /^[a-z]{2,3}(-[a-z0-9]{2,8})*$/

const codes = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .map((f) => f.slice(0, -3))
  .sort()

const bad = codes.filter((c) => !codePattern.test(c))
if (bad.length > 0) {
  console.error(
    `src/locales: file names must be lowercase language codes: ${bad.join(', ')}`
  )
  process.exit(1)
}
if (!codes.includes('en')) {
  console.error('src/locales/en.ts is missing (it defines the text keys)')
  process.exit(1)
}

/** zh-tw → zhTw */
const ident = (code) => code.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
/** Object key: quoted only when it is not a plain identifier */
const prop = (code) => (code.includes('-') ? `'${code}'` : code)

const lines = [
  '// Generated by scripts/gen-locales.js from the files in this folder; do not',
  '// edit. To add a language, add <code>.ts here and run `npm run locales`.',
  '',
  ...codes.map((c) => `import * as ${ident(c)} from './${c}'`),
  '',
  'export const locales = {',
  ...codes.map((c) =>
    ident(c) === c ? `  ${c},` : `  ${prop(c)}: ${ident(c)},`
  ),
  '}',
  '',
  '/** UI language code (the locale file name) */',
  'export type LangCode = keyof typeof locales',
  '',
  'export const langCodes = Object.keys(locales) as LangCode[]',
  '',
]
const output = lines.join('\n')

const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
if (process.argv.includes('--check')) {
  if (current.replace(/\r\n/g, '\n') !== output) {
    console.error(
      'src/locales/index.ts is out of date; run `npm run locales` and commit it'
    )
    process.exit(1)
  }
} else if (current !== output) {
  fs.writeFileSync(target, output)
  console.log(`src/locales/index.ts: ${codes.join(', ')}`)
}
